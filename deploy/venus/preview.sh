#!/usr/bin/env bash
# The preview stack on VENUS (docs/deployment-preview.md): one shared preview
# environment at preview.dupli1.com / manage-preview.dupli1.com, which the
# latest push to a preview/* pull request in any of the three repos deploys to.
#
#   deploy/venus/preview.sh setup [--ref <commit>]          # once, by hand
#   deploy/venus/preview.sh deploy backend sha-abc1234 --pr 12 --ref <commit>
#   deploy/venus/preview.sh deploy web sha-abc1234 --pr 34
#   deploy/venus/preview.sh reset web --pr 34               # PR closed
#
# deploy runs deploy.sh against the preview's compose project, env file,
# checkout and edge, so a preview rolls back the same way production does.
# Each target remembers which PR it is running; reset puts that target back
# on main (backend) or master (web, manage-web), but only if the closed PR is
# still the one deployed, so closing an older preview PR leaves a newer one up.
# Nothing here reads or writes /opt/dupli1.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
PREVIEW_HOME=${PREVIEW_HOME:-/opt/dupli1-preview}
OWNER=${GHCR_OWNER:-elug3}
REPO_URL=${REPO_URL:-https://github.com/$OWNER/dupli1.git}

export ENV_FILE=$PREVIEW_HOME/.env
export DEPLOY_DIR=$PREVIEW_HOME/repo
export COMPOSE_PROJECT=dupli1-preview
export COMPOSE_OVERRIDE=deploy/venus/docker-compose.preview.yml
export EDGE_URL=http://127.0.0.1:8090
export STORE_HOST=preview.dupli1.com
export MANAGE_HOST=manage-preview.dupli1.com

usage() {
  echo "usage: preview.sh setup [--ref <commit>]" >&2
  echo "       preview.sh deploy <backend|web|manage-web> <tag> --pr <n> [--ref <commit>]" >&2
  echo "       preview.sh reset <backend|web|manage-web> --pr <n>" >&2
  exit 2
}

dc() {
  docker compose -p "$COMPOSE_PROJECT" -f "$DEPLOY_DIR/deploy/venus/docker-compose.yml" \
    -f "$DEPLOY_DIR/$COMPOSE_OVERRIDE" --env-file "$ENV_FILE" "$@"
}

default_tag() { [[ $1 == backend ]] && echo main || echo master; }

check_target() {
  case $1 in backend | web | manage-web) ;; *) echo "unknown target: $1" >&2; exit 2 ;; esac
}

# Writes the preview .env with values of its own. Re-running keeps them.
write_env() {
  sudo install -d -m 700 -o "$(id -u)" -g "$(id -g)" "$PREVIEW_HOME" "$PREVIEW_HOME/secrets"
  umask 077
  [[ -s $PREVIEW_HOME/secrets/jwt_private_key.pem ]] ||
    openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$PREVIEW_HOME/secrets/jwt_private_key.pem" 2>/dev/null
  python3 - "$ENV_FILE" "$PREVIEW_HOME/secrets" <<'EOF'
import os, secrets, sys
env_path, secrets_dir = sys.argv[1:]
old = {}
if os.path.exists(env_path):
    for line in open(env_path):
        if "=" in line and not line.startswith("#"):
            k, v = line.rstrip("\n").split("=", 1)
            old[k] = v[1:-1] if v.startswith("'") else v

def keep(k, v):
    return old.get(k) or v

env = {
    "DUPLI1_SECRETS_DIR": secrets_dir,
    "PG_SUPERUSER_PASSWORD": keep("PG_SUPERUSER_PASSWORD", secrets.token_urlsafe(32)),
    "DB_APP_PASSWORD": keep("DB_APP_PASSWORD", secrets.token_urlsafe(32)),
    "S3_SECRET_KEY": keep("S3_SECRET_KEY", secrets.token_urlsafe(32)),
    "JWT_SECRET": keep("JWT_SECRET", secrets.token_urlsafe(48)),
    "DUPLI1_ORDER_SERVICE_EMAIL": keep("DUPLI1_ORDER_SERVICE_EMAIL", "dupli1-order@order.preview.dupli1.com"),
    "DUPLI1_ORDER_SERVICE_API_KEY": keep("DUPLI1_ORDER_SERVICE_API_KEY", "dk_live_" + secrets.token_urlsafe(32)),
    "DUPLI1_WEB_SERVICE_API_KEY": keep("DUPLI1_WEB_SERVICE_API_KEY", "dk_live_" + secrets.token_urlsafe(32)),
    "OWNER_EMAIL": keep("OWNER_EMAIL", os.environ.get("OWNER_EMAIL") or "owner@preview.dupli1.com"),
    "OWNER_PASSWORD": keep("OWNER_PASSWORD", secrets.token_urlsafe(18)),
    "PUBLIC_ORIGIN": "https://preview.dupli1.com",
    "MANAGE_ORIGIN": "https://manage-preview.dupli1.com",
    "SENTRY_ENVIRONMENT": "preview",
    # Optional, set by hand and kept: Sentry DSNs (the preview reports as
    # environment "preview"), NANO_* test-host credentials for card checkout.
    **{k: old[k] for k in old if k.startswith(("SENTRY_DSN_", "NANO_"))},
    # Each target's image tag; deploy.sh moves them.
    "DUPLI1_BACKEND_TAG": keep("DUPLI1_BACKEND_TAG", "main"),
    "DUPLI1_WEB_TAG": keep("DUPLI1_WEB_TAG", "master"),
    "DUPLI1_MANAGE_WEB_TAG": keep("DUPLI1_MANAGE_WEB_TAG", "master"),
}
for k, v in env.items():
    if "'" in v or "\n" in v:
        sys.exit(f"{k}: value can't be written as a single-quoted .env line")
with open(env_path + ".tmp", "w") as f:
    f.write("# Generated by deploy/venus/preview.sh setup. Preview only — no production value belongs here.\n")
    for k, v in env.items():
        f.write(f"{k}='{v}'\n")
os.replace(env_path + ".tmp", env_path)
print("wrote", env_path, "with", ", ".join(env))
EOF
}

# Pulls a target's image at a tag and tags it the way the compose file names it.
pull_target() {
  local target=$1 tag=$2 s
  case $target in
    backend)
      for s in auth product order cart payment profile notification support proxy; do
        docker pull -q "ghcr.io/$OWNER/dupli1-$s:$tag"
        docker tag "ghcr.io/$OWNER/dupli1-$s:$tag" "dupli1-prod/$s:$tag"
      done ;;
    web)
      docker pull -q "ghcr.io/$OWNER/dupli1-web:$tag"
      docker tag "ghcr.io/$OWNER/dupli1-web:$tag" "dupli1-prod/web:$tag" ;;
    manage-web)
      docker pull -q "ghcr.io/$OWNER/dupli1-manage-web:$tag"
      docker tag "ghcr.io/$OWNER/dupli1-manage-web:$tag" "dupli1-prod/manage-web-container:$tag" ;;
  esac
}

# The preview's edge, started on its own so deploy.sh's health checks have
# something to ask. --no-deps: deploy.sh brings up the target's services.
edge_up() { dc up -d --no-deps preview-edge; }

cmd=${1:-}; shift || true
case $cmd in
  setup)
    REF=main
    if [[ ${1:-} == --ref ]]; then REF=${2:?}; shift 2; fi
    [[ $# -eq 0 ]] || usage
    docker network inspect dupli1_default >/dev/null ||
      { echo "production network dupli1_default not found; is the production stack up?" >&2; exit 1; }
    write_env
    if [[ ! -d $DEPLOY_DIR/.git ]]; then
      git clone -q --depth 1 "$REPO_URL" "$DEPLOY_DIR"
    fi
    git -C "$DEPLOY_DIR" fetch -q --depth 1 origin "$REF"
    git -C "$DEPLOY_DIR" checkout -qf --detach FETCH_HEAD
    # shellcheck disable=SC1090
    set -a; . "$ENV_FILE"; set +a
    pull_target backend "$DUPLI1_BACKEND_TAG"
    pull_target web "$DUPLI1_WEB_TAG"
    pull_target manage-web "$DUPLI1_MANAGE_WEB_TAG"
    dc up -d
    echo "preview stack up from $(git -C "$DEPLOY_DIR" rev-parse --short HEAD)"
    echo "owner: $OWNER_EMAIL (password: OWNER_PASSWORD in $ENV_FILE)"
    echo "local check: curl -H 'Host: preview.dupli1.com' $EDGE_URL/gateway/health"
    ;;

  deploy)
    [[ $# -ge 4 ]] || usage
    TARGET=$1; TAG=$2; shift 2
    check_target "$TARGET"
    PR=""; REF=()
    while [[ $# -gt 0 ]]; do
      case $1 in
        --pr) PR=${2:?}; shift 2 ;;
        --ref) REF=(--ref "${2:?}"); shift 2 ;;
        *) usage ;;
      esac
    done
    [[ $PR =~ ^[0-9]+$ ]] || usage
    [[ -f $ENV_FILE ]] || { echo "no $ENV_FILE: run preview.sh setup first" >&2; exit 1; }
    edge_up
    "$HERE/deploy.sh" "${REF[@]}" "$TARGET" "$TAG"
    echo "$PR" >"$PREVIEW_HOME/$TARGET.pr"
    echo "preview $TARGET is PR #$PR ($TAG)"
    ;;

  reset)
    [[ $# -eq 3 && $2 == --pr ]] || usage
    TARGET=$1; PR=$3
    check_target "$TARGET"
    if [[ $(cat "$PREVIEW_HOME/$TARGET.pr" 2>/dev/null) != "$PR" ]]; then
      echo "preview $TARGET is not running PR #$PR; leaving it as it is"
      exit 0
    fi
    TAG=$(default_tag "$TARGET")
    REF=()
    [[ $TARGET != backend ]] || REF=(--ref main)
    edge_up
    "$HERE/deploy.sh" "${REF[@]}" "$TARGET" "$TAG"
    rm -f "$PREVIEW_HOME/$TARGET.pr"
    echo "preview $TARGET is back on $TAG"
    ;;

  *) usage ;;
esac
